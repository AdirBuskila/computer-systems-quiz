def arith(target, a=4, b=5, keep=True):
    samples = [(x, y) for x in (-7, -1, 0, 1, 3, 11) for y in (-5, 0, 2, 9)]
    def test(code):
        for x, y in samples:
            R, _, _ = run(code, {a: x, b: y})
            if R[a] != target(x, y) or (keep and R[b] != y):
                return False
        return True
    return test

