def cdo(cond, kind):
    def f(n):
        x = 0
        it = 0
        if kind == "while":
            while cond(n):
                x += 2; n -= 1; it += 1
                if it > 100: raise RuntimeError
        else:
            while True:
                x += 2; n -= 1; it += 1
                if it > 100: raise RuntimeError
                if not cond(n): break
        return x
    return f
